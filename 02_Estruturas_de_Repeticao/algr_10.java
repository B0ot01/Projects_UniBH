public class algr_10 {
    public static void main(String[] args) {
        double polegada = 1;
        double centimetro = 2.54;

        for (polegada = 1; polegada <= 20; polegada++) {
            System.out.println(polegada + " Polegada em Centímetro: " + (polegada * centimetro));
        }
    }
}
